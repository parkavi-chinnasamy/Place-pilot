import React, { useState, useEffect } from 'react';
import { recAPI, jobRolesAPI, readinessAPI } from '../../services/api';
import { Card, PageHeader, LoadingSpinner, DemoBanner, Btn } from '../../components/common/Card';
import { toast } from 'react-toastify';
import { FiRefreshCw, FiExternalLink } from 'react-icons/fi';

export default function Recommendations() {
  const [recs, setRecs] = useState([]);
  const [roles, setRoles] = useState([]);
  const [selectedRole, setSelectedRole] = useState('');
  const [loading, setLoading] = useState(false);
  const [generating, setGenerating] = useState(false);

  useEffect(() => {
    jobRolesAPI.list().then(r => setRoles(r.data));
    loadRecs();
  }, []);

  const loadRecs = async (roleId) => {
    setLoading(true);
    try { const res = await recAPI.get(roleId); setRecs(res.data); } catch {}
    finally { setLoading(false); }
  };

  const regenerate = async () => {
    if (!selectedRole) return toast.warning('Select a role and calculate readiness first');
    setGenerating(true);
    try {
      await readinessAPI.calculate(selectedRole);
      await loadRecs(selectedRole);
      toast.success('Recommendations refreshed!');
    } catch (e) { toast.error(e.response?.data?.detail || 'Failed'); }
    finally { setGenerating(false); }
  };

  const rec = recs[0];

  return (
    <div>
      <DemoBanner message={rec?.is_demo ? 'Demo recommendations generated by rule-based engine (no Gemini API key). Add GEMINI_API_KEY to .env for real AI recommendations.' : 'Recommendations powered by Google Gemini'} />
      <PageHeader title="AI Recommendations" subtitle="Personalised action plan based on your skill profile"
        action={
          <div style={{ display:'flex', gap:8, alignItems:'center' }}>
            <select value={selectedRole} onChange={e => { setSelectedRole(e.target.value); loadRecs(e.target.value); }}
              style={{ padding:'9px 14px', border:'1.5px solid #e2e8f0', borderRadius:8, fontSize:13, background:'white' }}>
              <option value="">All roles</option>
              {roles.map(r => <option key={r.id} value={r.id}>{r.name}</option>)}
            </select>
            <Btn onClick={regenerate} disabled={generating}><FiRefreshCw /> {generating?'Generating…':'Refresh'}</Btn>
          </div>
        }
      />

      {loading ? <LoadingSpinner /> : !rec ? (
        <Card style={{ textAlign:'center', padding:60 }}>
          <div style={{ fontSize:48, marginBottom:16 }}>🤖</div>
          <h3 style={{ fontSize:16, fontWeight:600, marginBottom:8 }}>No recommendations yet</h3>
          <p style={{ color:'#94a3b8', fontSize:13, marginBottom:20 }}>Calculate your readiness to generate a personalised action plan</p>
          <a href="/readiness" style={{ display:'inline-block', padding:'10px 24px', background:'#4f46e5', color:'white', borderRadius:8, fontWeight:600, fontSize:13, textDecoration:'none' }}>Go to Readiness</a>
        </Card>
      ) : (
        <>
          {/* Summary */}
          <Card style={{ marginBottom:20, background:'linear-gradient(135deg,#1e1b4b,#312e81)', color:'white', border:'none' }}>
            <div style={{ display:'flex', justifyContent:'space-between', alignItems:'flex-start', flexWrap:'wrap', gap:16 }}>
              <div style={{ flex:1 }}>
                <div style={{ fontSize:11, color:'rgba(255,255,255,0.4)', marginBottom:8, letterSpacing:'0.06em', fontWeight:700 }}>
                  {rec.generated_by === 'gemini' ? '🤖 POWERED BY GEMINI AI' : '📊 DEMO RECOMMENDATION ENGINE'} · {rec.job_role_name}
                </div>
                <p style={{ fontSize:15, lineHeight:1.8, color:'rgba(255,255,255,0.85)' }}>{rec.summary}</p>
              </div>
            </div>
          </Card>

          <div style={{ display:'grid', gridTemplateColumns:'1fr 1fr', gap:20, marginBottom:20 }}>
            {/* Skill actions */}
            <Card>
              <h3 style={{ fontWeight:700, marginBottom:16, fontSize:15 }}>🎯 Priority Skill Actions</h3>
              {(rec.skill_actions||[]).map((a,i) => (
                <div key={i} style={{ marginBottom:20, paddingBottom:20, borderBottom:i<rec.skill_actions.length-1?'1px solid #f1f5f9':'none' }}>
                  <div style={{ display:'flex', alignItems:'center', gap:10, marginBottom:8 }}>
                    <span style={{ background:'#4f46e5', color:'white', width:24, height:24, borderRadius:'50%', display:'flex', alignItems:'center', justifyContent:'center', fontSize:12, fontWeight:700, flexShrink:0 }}>{i+1}</span>
                    <div>
                      <span style={{ fontWeight:700, fontSize:14 }}>{a.skill_label || a.skill?.toUpperCase()}</span>
                      <span style={{ marginLeft:8, fontSize:12, color:'#94a3b8' }}>{a.current_score?.toFixed(0)} → {a.target_score?.toFixed(0)}</span>
                    </div>
                  </div>
                  <p style={{ fontSize:13, color:'#64748b', marginBottom:8, paddingLeft:34 }}>{a.why_matters}</p>
                  <div style={{ paddingLeft:34 }}>
                    <div style={{ fontSize:12, fontWeight:600, color:'#475569', marginBottom:4 }}>What to learn:</div>
                    <ul style={{ paddingLeft:16, margin:0 }}>
                      {(a.what_to_learn||[]).map((t,j) => <li key={j} style={{ fontSize:12, color:'#64748b', marginBottom:2 }}>{t}</li>)}
                    </ul>
                    <div style={{ fontSize:12, background:'#f0fdf4', padding:'8px 12px', borderRadius:6, marginTop:8, color:'#166534', borderLeft:'3px solid #10b981' }}>
                      📌 {a.practice}
                    </div>
                  </div>
                </div>
              ))}
            </Card>

            {/* Weekly plan */}
            <Card>
              <h3 style={{ fontWeight:700, marginBottom:16, fontSize:15 }}>📅 4-Week Plan</h3>
              {(rec.weekly_plan||[]).map((w,i) => (
                <div key={i} style={{ marginBottom:16, padding:'14px 16px', background:i===0?'#eef2ff':'#f8fafc', borderRadius:10, border:`1px solid ${i===0?'#c7d2fe':'#e2e8f0'}` }}>
                  <div style={{ display:'flex', justifyContent:'space-between', alignItems:'center', marginBottom:8 }}>
                    <span style={{ fontWeight:700, fontSize:13 }}>Week {w.week} — {w.focus}</span>
                    {i===0 && <span style={{ fontSize:11, background:'#4f46e5', color:'white', padding:'2px 8px', borderRadius:12, fontWeight:600 }}>Current</span>}
                  </div>
                  <ul style={{ paddingLeft:16, margin:0, marginBottom:8 }}>
                    {(w.tasks||[]).map((t,j) => <li key={j} style={{ fontSize:12, color:'#475569', marginBottom:3 }}>{t}</li>)}
                  </ul>
                  <div style={{ fontSize:12, color:'#4f46e5', fontWeight:600 }}>🎯 Goal: {w.goal}</div>
                </div>
              ))}
            </Card>
          </div>

          <div style={{ display:'grid', gridTemplateColumns:'1fr 1fr', gap:20 }}>
            {/* Resources */}
            <Card>
              <h3 style={{ fontWeight:700, marginBottom:16, fontSize:15 }}>📚 Recommended Resources</h3>
              {(rec.resources||[]).map((r,i) => (
                <div key={i} style={{ display:'flex', alignItems:'center', justifyContent:'space-between', padding:'10px 14px', background:'#f8fafc', borderRadius:8, marginBottom:8 }}>
                  <div>
                    <div style={{ fontWeight:600, fontSize:13 }}>{r.title}</div>
                    <div style={{ fontSize:11, color:'#94a3b8', marginTop:2 }}>{r.type} · {r.skill}</div>
                  </div>
                  {r.url && <a href={r.url} target="_blank" rel="noreferrer" style={{ color:'#4f46e5', fontSize:16 }}><FiExternalLink /></a>}
                </div>
              ))}
            </Card>

            {/* Next steps */}
            <Card>
              <h3 style={{ fontWeight:700, marginBottom:16, fontSize:15 }}>⚡ Immediate Next Steps</h3>
              {(rec.next_steps||[]).map((s,i) => (
                <div key={i} style={{ display:'flex', gap:12, marginBottom:12, padding:'10px 14px', background:'#f8fafc', borderRadius:8 }}>
                  <span style={{ fontWeight:800, color:'#4f46e5', fontSize:14, flexShrink:0 }}>{i+1}.</span>
                  <span style={{ fontSize:13, color:'#475569', lineHeight:1.6 }}>{s}</span>
                </div>
              ))}
            </Card>
          </div>
        </>
      )}
    </div>
  );
}
